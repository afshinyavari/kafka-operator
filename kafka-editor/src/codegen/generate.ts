/** Generate the full Quarkus project for a topology document. */
export function generateProject(doc: ProjectDocument): GeneratedFile[] {
  const files: GeneratedFile[] = [
    { path: 'pom.xml', content: POM_XML },
    {
      path: 'src/main/resources/application.properties',
      content: applicationProperties(doc),
    },
    {
      path: `${JAVA_DIR}/TopologyProducer.java`,
      content: generateTopology(doc),
    },
  ]

  // Java type files — record types (with nested classes) and operator outputs.
  // Deduplicate by path so colliding class names produce one file.
  const seen = new Set<string>(files.map((f) => f.path))
  const addJava = (className: string, content: string) => {
    const path = `${JAVA_DIR}/${className}.java`
    if (seen.has(path)) return
    seen.add(path)
    files.push({ path, content })
  }
  for (const recordType of doc.recordTypes) {
    for (const cls of generateRecordClasses(recordType, doc.recordTypes)) {
      addJava(cls.className, cls.content)
    }
  }
  for (const outputType of computeOutputTypes(doc).values()) {
    addJava(outputType.className, generateOutputRecord(outputType))
  }

  files.push(...generateConnectorConfigs(doc))
  return files
}
