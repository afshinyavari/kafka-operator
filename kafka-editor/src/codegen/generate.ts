/** One generated source file. */
export interface GeneratedFile {
  path: string
  content: string
}

const JAVA_DIR = 'src/main/java/org/acme/kafka'

function applicationProperties(doc: ProjectDocument): string {
  const appId =
    (doc.meta.name || 'kafka-streams-app')
      .trim()
      .replace(/\s+/g, '-')
      .toLowerCase() || 'kafka-streams-app'
  const topics = doc.catalog.topics.map((t) => t.name).join(',')
  return `# Generated by Kafka Editor
quarkus.kafka-streams.application-id=${appId}
quarkus.kafka-streams.bootstrap-servers=localhost:9092
quarkus.kafka-streams.topics=${topics}

kafka.bootstrap.servers=localhost:9092
`
}

